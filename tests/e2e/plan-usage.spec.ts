import { test, expect } from "@playwright/test";
test.setTimeout(180_000);
test.use({ extraHTTPHeaders: { "Cache-Control": "no-cache" } });
for (const width of [390, 1280]) {
test(`avisos de uso y estado de los botones de plan a ${width}px`, async ({page, request}) => {
 await page.setViewportSize({width, height: 900});
 await request.post("http://127.0.0.1:54329/test/reset");
 await request.post("http://127.0.0.1:54329/test/plan", {data: {code: "growth"}});
 await request.post("http://127.0.0.1:54329/test/usage", {data: {usage: {operators: 11, pallets: 3001, month_start: "2026-10-01", pallets_complete: false}}});
 await page.goto("/login");
 await page.getByLabel("Email").fill("logistica@trazflow.test");
 await page.getByLabel("Contraseña").fill("test1234");
 await page.getByRole("button", {name: "Ingresar", exact: true}).click();
 await expect(page).toHaveURL(/dashboard/);
 await page.goto("/dashboard/account");
 await expect(page.getByText("Tu uso supera los límites del plan asignado: Growth.", {exact:true})).toBeVisible();
 await expect(page.getByRole("alert").filter({hasText:"plan asignado: Growth"})).toHaveClass(/feedback-danger/);
 await expect(page.locator("#equipamiento")).not.toHaveAttribute("open");
 await expect(page.getByText(/El consumo de pallets de este mes puede estar incompleto/)).toBeVisible();
 const starter = page.getByRole("article", {name:"Starter", exact:true}).getByRole("button");
 const enterprise = page.getByRole("article", {name:"Enterprise", exact:true}).getByRole("button");
 const current = page.getByRole("article", {name:"Growth", exact:true}).getByRole("button");
 await expect(current).toHaveText("Plan actual");
 await expect(current).toBeDisabled();
 await expect(starter).toHaveText("Seleccionar plan");
 await expect(starter).toBeEnabled();
 await starter.click();
 await expect(starter).toHaveText("Seleccionado");
 await expect(starter).toHaveAccessibleName("Seleccionado: Starter");
 await expect(starter).toBeDisabled();
 await expect(enterprise).toHaveText("Seleccionar plan");
 await expect(enterprise).toBeEnabled();
 await expect(page.getByText("Tu uso supera los límites del plan inferior seleccionado: Starter.", {exact:true})).toBeVisible();
 await expect(page.getByText("Tu uso supera los límites del plan seleccionado provisionalmente: Starter.", {exact:true})).toHaveCount(0);
 await page.getByRole("link", {name:"Ver resumen del plan", exact:true}).click();
 await expect(page).toHaveURL(/\/dashboard\/account\/review\?selectedPlan=starter/);
 await expect(page.getByRole("heading", {name:"Resumen del plan", exact:true})).toBeVisible();
 await expect(page.getByText("Tu uso supera los límites del plan inferior seleccionado: Starter.", {exact:true})).toBeVisible();
 await page.getByRole("link", {name:"Volver a comparar planes", exact:true}).click();
 await page.getByRole("button", {name:"Quitar selección", exact:true}).click();
 await expect(starter).toHaveText("Seleccionar plan");
 await expect(starter).toBeEnabled();
 await expect(current).toBeDisabled();
 await starter.click();
 await expect(page.getByRole("link", {name:"Ver resumen del plan", exact:true})).toBeVisible();
 await enterprise.click();
 await expect(enterprise).toHaveText("Seleccionado");
 await expect(enterprise).toBeDisabled();
 await expect(starter).toBeEnabled();
 await expect(page.getByText(/Tu uso supera los límites del plan inferior seleccionado/)).toHaveCount(0);
 await expect(page.getByText(/Tu uso supera los límites del plan seleccionado provisionalmente/)).toHaveCount(0);
 await request.post("http://127.0.0.1:54329/test/usage", {data:{unavailable:true}});
 await page.reload();
 await expect(page.getByText(/No pudimos consultar el consumo/)).toBeVisible();
 await page.getByRole("button", {name:"Seleccionar plan Starter", exact:true}).click();
 await expect(page.getByRole("link", {name:"Ver resumen del plan", exact:true})).toBeVisible();
});

}
